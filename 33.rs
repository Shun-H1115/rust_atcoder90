// ==========================================================================
// 典型90 #033  Not Too Bright  (★2)
// 問題: https://atcoder.jp/contests/typical90/tasks/typical90_ag
// ==========================================================================
// 【アルゴリズム】 場合分け（1行 or 1列なら全部点灯可、それ以外は2×2ごとに1個）
// 【計算量】       O(1)
// 【学習計画】     第1週（★2）
//
// 【このファイルで覚えるRust文法】
//   - if 式の値を let で受ける（Py の三項演算子）
//   - 整数除算で切り上げ: (h + 1) / 2 … Py: (h + 1) // 2
//
// 【Pythonで書くと（考え方の対応）】
//   print(H*W if H == 1 or W == 1 else ((H+1)//2) * ((W+1)//2))
// ==========================================================================

use proconio::input;

fn main() {
    input! {
        h: usize,
        w: usize,
    }

    // if は式なので値を返す。各ブロックの最後の式（; なし）が値になる。末尾の }; の ; を忘れずに。
    let answer = if h == 1 || w == 1 {
        h * w
    } else {
        ((h + 1) / 2) * ((w + 1) / 2)
    };

    println!("{}", answer);
}
